<?php

namespace App\Http\Controllers\Api\Support\OpenApi;

use App\Support\Abilities;
use Illuminate\Routing\Route;
use Illuminate\Routing\Router;

/**
 * Builds the OpenAPI 3.1 document from the application's real routes plus the descriptions in Operations and Schemas.
 * Because the route list is the source of truth, the spec cannot drift: a route without an entry in Operations, or an entry
 * without a route, is an error (see `php artisan api:openapi`).
 */
class Builder
{
    /** Segment after /admin (or first segment) => tag. */
    private const TAGS = [
        '' => 'Meta', 'openapi.json' => 'Meta', 'auth' => 'Authentication', 'me' => 'Account', 'products' => 'Catalog', 'gateways' => 'Catalog',
        'orders' => 'Orders', 'services' => 'Services', 'invoices' => 'Invoices', 'quotes' => 'Quotes', 'payments' => 'Invoices', 'payment-methods' => 'Payment methods',
        'tickets' => 'Support', 'ticket-departments' => 'Support',
    ];

    private const ADMIN_TAGS = [
        'dashboard' => 'Dashboard', 'activity' => 'Activity', 'clients' => 'Clients', 'users' => 'Clients', 'staff-users' => 'Staff users', 'services' => 'Services', 'products' => 'Products',
        'product-groups' => 'Products', 'modules' => 'Products', 'servers' => 'Servers', 'invoices' => 'Invoices', 'payments' => 'Payments', 'quotes' => 'Quotes',
        'tax-rates' => 'Tax rates', 'settings' => 'Settings', 'plugins' => 'Plugins', 'api-tokens' => 'API tokens', 'webhooks' => 'Webhooks', 'events' => 'Webhooks',
        'me' => 'Meta', 'abilities' => 'Meta', 'autopay' => 'Payments',
        'tickets' => 'Support', 'ticket-departments' => 'Support', 'ticket-fields' => 'Support',
    ];

    /** Path parameters that are not numeric ids. */
    private const STRING_PARAMS = ['slug', 'action', 'section'];

    public function __construct(private readonly Router $router) {}

    /** @return array<string, mixed> */
    public function build(): array
    {
        $operations = Operations::all();
        $paths = [];
        $seen = [];
        $missing = [];

        foreach ($this->routes() as $route) {
            $name = $this->key($route);
            $meta = $operations[$name] ?? null;
            if ($meta === null) {
                $missing[] = $name.' ('.$route->uri().')';

                continue;
            }
            $seen[$name] = true;
            foreach ($route->methods() as $method) {
                if ($method === 'HEAD') {
                    continue;
                }
                $paths[$this->path($route)][strtolower($method)] = $this->operation($route, $name, $meta);
            }
        }
        $stale = array_keys(array_diff_key($operations, $seen));
        if ($missing || $stale) {
            throw new \RuntimeException(trim(
                ($missing ? "Routes without documentation in Operations.php:\n  - ".implode("\n  - ", $missing)."\n" : '')
                .($stale ? "Operations.php entries without a route:\n  - ".implode("\n  - ", $stale) : '')
            ));
        }

        return [
            'openapi' => '3.1.0',
            'info' => [
                'title' => 'Tidemark Billing API',
                'version' => '1.0.0',
                'description' => 'REST API for Tidemark Billing. Customer tokens use the client endpoints; staff tokens use /admin/*. Amounts are integers in minor units. Errors use {error:{code,message,details?}}. Generated by `php artisan api:openapi`.',
            ],
            'servers' => [['url' => '/api/v1']],
            'security' => [['bearerAuth' => []]],
            'tags' => array_map(fn ($t) => ['name' => $t], $this->tagNames($paths)),
            'components' => [
                'securitySchemes' => ['bearerAuth' => ['type' => 'http', 'scheme' => 'bearer', 'description' => 'Token from POST /auth/token']],
                'schemas' => $this->schemas(),
            ],
            'paths' => $paths,
        ];
    }

    /** The routes that belong to the API (plugins may add their own under /api/v1/x/, which they document themselves). @return array<int, Route> */
    public function routes(): array
    {
        return array_values(array_filter(
            $this->router->getRoutes()->getRoutes(),
            fn (Route $r) => str_starts_with($r->uri(), 'api/v1') && ! str_starts_with($r->uri(), 'api/v1/x/'),
        ));
    }

    /** "admin.clients.index" for the route named "api.admin.clients.index". */
    public function key(Route $route): string
    {
        $name = (string) $route->getName();
        if ($name === '') {
            throw new \RuntimeException('API route without a name: '.$route->uri());
        }

        return preg_replace('/^api\./', '', $name);
    }

    private function path(Route $route): string
    {
        $path = substr($route->uri(), strlen('api/v1'));

        return $path === '' ? '/' : $path;
    }

    /** @param  array<int, mixed>  $meta @return array<string, mixed> */
    private function operation(Route $route, string $name, array $meta): array
    {
        [$summary, $res] = $meta;
        $body = $meta[2] ?? null;
        $query = $meta[3] ?? [];
        $middleware = $route->gatherMiddleware();
        $admin = str_starts_with($route->uri(), 'api/v1/admin');
        $authenticated = (bool) array_filter($middleware, fn ($m) => is_string($m) && str_starts_with($m, 'auth.api'));
        $abilities = [];
        foreach ($middleware as $m) {
            if (is_string($m) && str_starts_with($m, 'ability:')) {
                $abilities = array_merge($abilities, explode(',', substr($m, 8)));
            }
        }
        foreach ($abilities as $a) {
            if (! Abilities::isValid($a)) {
                throw new \RuntimeException("Route $name requires unknown ability \"$a\". Add it to App\\Support\\Abilities.");
            }
        }

        $parameters = [];
        foreach ($route->parameterNames() as $param) {
            $parameters[] = ['name' => $param, 'in' => 'path', 'required' => true, 'schema' => $this->pathParamSchema($param, $admin)];
        }
        foreach ($query as $qName => $spec) {
            $parameters[] = ['name' => $qName, 'in' => 'query', 'required' => false] + $this->paramSchema($spec);
        }
        if (($res['kind'] ?? null) === 'page') {
            $parameters[] = ['name' => 'page', 'in' => 'query', 'required' => false, 'schema' => ['type' => 'integer', 'minimum' => 1]];
            $parameters[] = ['name' => 'per_page', 'in' => 'query', 'required' => false, 'schema' => ['type' => 'integer', 'minimum' => 1, 'maximum' => 100, 'default' => 25]];
        }

        $description = [];
        if ($abilities) {
            $description[] = 'Required ability: '.implode(', ', array_map(fn ($a) => "`$a`", $abilities)).' (tokens without an ability list may do everything their owner can).';
        } elseif ($authenticated) {
            $description[] = 'Any valid token'.($admin ? ' of a staff user' : '').' (no ability needed).';
        }
        if (str_contains($summary, 'administrators only') || str_contains($summary, '(administrators only') || str_contains($summary, 'Administrators only')) {
            $description[] = 'Administrators only: staff tokens of non-admin users get 403.';
        }

        $op = [
            'tags' => [$this->tag($route, $admin)],
            'summary' => $summary,
            'operationId' => lcfirst(str_replace(' ', '', ucwords(str_replace(['.', '-'], ' ', $name)))),
        ];
        if ($description) {
            $op['description'] = implode(' ', $description);
        }
        $op['security'] = $authenticated ? [['bearerAuth' => []]] : [];
        if ($parameters) {
            $op['parameters'] = $parameters;
        }
        if ($body !== null) {
            $op['requestBody'] = ['required' => true, 'content' => ['application/json' => ['schema' => Dsl::type($body)]]];
        }
        $op['responses'] = $this->responses($res, $authenticated, (bool) $abilities || $admin, ! empty($route->parameterNames()), $body !== null || $route->methods()[0] !== 'GET');

        return $op;
    }

    /** @param  array<string, mixed>  $res @return array<string, mixed> */
    private function responses(array $res, bool $authenticated, bool $forbidden, bool $hasParams, bool $writes): array
    {
        $kind = $res['kind'];
        $status = $res['status'] ?? 200;
        $schema = isset($res['schema']) ? Dsl::type($res['schema']) : null;
        $extra = $res['extra'] ?? [];

        $out = [];
        if ($kind === 'none') {
            $out[(string) $status] = ['description' => 'No content'];
        } elseif ($kind === 'file') {
            $out[(string) $status] = ['description' => 'The file, sent as an attachment', 'content' => [$res['media'] => ['schema' => ['type' => 'string', 'format' => 'binary']]]];
        } else {
            $content = match ($kind) {
                'raw' => $schema,
                'one' => ['type' => 'object', 'properties' => ['data' => $schema] + $extra],
                'many' => ['type' => 'object', 'properties' => ['data' => ['type' => 'array', 'items' => $schema]] + $extra],
                'page' => ['allOf' => [Dsl::ref('Pagination'), ['type' => 'object', 'properties' => ['data' => ['type' => 'array', 'items' => $schema]] + $extra]]],
            };
            $out[(string) $status] = ['description' => $status === 201 ? 'Created' : 'Success', 'content' => ['application/json' => ['schema' => $content]]];
        }
        $error = fn (string $d) => ['description' => $d, 'content' => ['application/json' => ['schema' => Dsl::ref('Error')]]];
        if ($authenticated) {
            $out['401'] = $error('Missing or invalid token');
        }
        if ($forbidden) {
            $out['403'] = $error('Forbidden: wrong kind of token, missing ability, or administrators only');
        }
        if ($hasParams && $authenticated) {
            $out['404'] = $error('Not found');
        }
        if ($writes) {
            $out['422'] = $error('Validation or business rule error');
        }
        $out['429'] = $error('Rate limited');
        foreach ($res['errors'] ?? [] as $code => $description) { // documented in Operations for responses the generic rules above cannot know
            $out[(string) $code] = (int) $code < 300 ? ['description' => $description] + array_diff_key($out[(string) $status], ['description' => 1]) : $error($description);
        }
        ksort($out);

        return $out;
    }

    /** @return array<string, mixed> */
    private function pathParamSchema(string $param, bool $admin): array
    {
        if ($admin) {
            return in_array($param, ['method', 'attachment'], true) ? ['type' => 'string', 'format' => 'uuid'] : (in_array($param, self::STRING_PARAMS, true) ? ['type' => 'string'] : ['type' => 'integer']);
        }

        return in_array($param, ['service', 'invoice', 'quote', 'method', 'ticket', 'attachment'], true) ? ['type' => 'string', 'format' => 'uuid'] : ['type' => 'string'];
    }

    /** @param  string|array<string, mixed>  $spec @return array<string, mixed> */
    private function paramSchema(string|array $spec): array
    {
        $description = is_array($spec) && ! isset($spec['type']) && isset($spec[1]) ? $spec[1] : null;

        return ['schema' => Dsl::type(is_array($spec) && ! isset($spec['type']) ? $spec[0] : $spec)] + ($description ? ['description' => $description] : []);
    }

    private function tag(Route $route, bool $admin): string
    {
        $segments = explode('/', substr($this->path($route), 1));
        if ($admin) {
            return 'Admin: '.(self::ADMIN_TAGS[$segments[1] ?? ''] ?? ucfirst($segments[1] ?? 'Other'));
        }

        return self::TAGS[$segments[0]] ?? ucfirst($segments[0]);
    }

    /** @param  array<string, mixed>  $paths @return array<int, string> */
    private function tagNames(array $paths): array
    {
        $tags = [];
        foreach ($paths as $ops) {
            foreach ($ops as $op) {
                $tags[$op['tags'][0]] = true;
            }
        }

        return array_keys($tags);
    }

    /** @return array<string, mixed> */
    private function schemas(): array
    {
        return Schemas::all();
    }
}
